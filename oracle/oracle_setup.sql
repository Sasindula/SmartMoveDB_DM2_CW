CREATE OR REPLACE PROCEDURE Update_Driver_Duty_State (
    in_driver_id IN NUMBER,
    in_new_state IN VARCHAR2
)
AS
    v_new_state VARCHAR2(20);
BEGIN
    v_new_state := TRIM(in_new_state);

    IF v_new_state IS NULL OR
       v_new_state NOT IN (
           'Active',
           'On Trip',
           'On Leave'
       )
    THEN
        RAISE_APPLICATION_ERROR(
            -20010,
            'Invalid driver status'
        );
    END IF;

    UPDATE DRIVER
    SET STATUS = v_new_state
    WHERE DRIVER_ID = in_driver_id;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20011,
            'Driver does not exist'
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE(
        'Driver status updated successfully.'
    );

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(
            'Error: ' || SQLERRM
        );
        RAISE;
END Update_Driver_Duty_State;
