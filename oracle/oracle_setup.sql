CREATE OR REPLACE PROCEDURE Fetch_Driver_Schedule (
    in_driver_id IN NUMBER
)
AS
    v_driver_name DRIVER.DRIVER_NAME%TYPE;
    v_trip_count NUMBER := 0;

    CURSOR c_schedule IS
        SELECT
            t.TRIP_ID,
            r.SOURCE,
            r.DESTINATION,
            v.PLATE_NUMBER,
            v.VEHICLE_TYPE,
            t.DEPARTURE_TIME,
            t.ARRIVAL_TIME,
            t.FARE_AMOUNT
        FROM TRIP t
        JOIN ROUTE r
            ON t.ROUTE_ID = r.ROUTE_ID
        JOIN VEHICLE v
            ON t.VEHICLE_ID = v.VEHICLE_ID
        WHERE t.DRIVER_ID = in_driver_id
        ORDER BY t.DEPARTURE_TIME;

BEGIN
    -- Check whether driver exists
    SELECT DRIVER_NAME
    INTO v_driver_name
    FROM DRIVER
    WHERE DRIVER_ID = in_driver_id;

    DBMS_OUTPUT.PUT_LINE(
        '===== DRIVER SCHEDULE REPORT ====='
    );

    DBMS_OUTPUT.PUT_LINE(
        'Driver: ' || v_driver_name
    );

    FOR rec IN c_schedule LOOP
        v_trip_count := v_trip_count + 1;

        DBMS_OUTPUT.PUT_LINE(
            'Trip #' || rec.TRIP_ID ||
            ' | Route: ' || rec.SOURCE ||
            ' -> ' || rec.DESTINATION ||
            ' | Vehicle: ' || rec.PLATE_NUMBER ||
            ' | Departure: ' ||
            TO_CHAR(
                rec.DEPARTURE_TIME,
                'YYYY-MM-DD HH24:MI'
            ) ||
            ' | Arrival: ' ||
            TO_CHAR(
                rec.ARRIVAL_TIME,
                'YYYY-MM-DD HH24:MI'
            ) ||
            ' | Fare: LKR ' || rec.FARE_AMOUNT
        );
    END LOOP;

    IF v_trip_count = 0 THEN
        DBMS_OUTPUT.PUT_LINE(
            'No trips assigned to this driver.'
        );
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE(
            'Driver does not exist.'
        );

    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(
            'Error: ' || SQLERRM
        );
        RAISE;
END Fetch_Driver_Schedule;
