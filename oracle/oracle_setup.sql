CREATE OR REPLACE FUNCTION Calc_Period_Earnings (
    in_from_date IN DATE,
    in_to_date   IN DATE
)
RETURN NUMBER
IS
    v_total NUMBER(12,2);
BEGIN
    IF in_from_date IS NULL
       OR in_to_date IS NULL
       OR TRUNC(in_from_date) > TRUNC(in_to_date)
    THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'Invalid date range'
        );
    END IF;

    SELECT NVL(SUM(AMOUNT), 0)
    INTO v_total
    FROM PAYMENT
    WHERE PAYMENT_DATE >= TRUNC(in_from_date)
      AND PAYMENT_DATE < TRUNC(in_to_date) + 1
      AND UPPER(PAYMENT_STATUS) IN ('PAID', 'DEMO PAID');

    RETURN v_total;

EXCEPTION
    WHEN OTHERS THEN
        RAISE;
END Calc_Period_Earnings;
