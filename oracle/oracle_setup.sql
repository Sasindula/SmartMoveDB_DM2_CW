CREATE OR REPLACE PROCEDURE Cancel_Passenger_Ticket (
    in_booking_id   IN NUMBER,
    in_passenger_id IN NUMBER
)
AS
    v_status         BOOKING.STATUS%TYPE;
    v_departure_time TRIP.DEPARTURE_TIME%TYPE;
    v_payment_count  NUMBER;
BEGIN
    -- Lock booking and check ownership
    SELECT b.STATUS, t.DEPARTURE_TIME
    INTO v_status, v_departure_time
    FROM BOOKING b
    JOIN TRIP t
        ON b.TRIP_ID = t.TRIP_ID
    WHERE b.BOOKING_ID = in_booking_id
      AND b.PASSENGER_ID = in_passenger_id
    FOR UPDATE OF b.STATUS;

    -- Check current booking status
    IF v_status = 'Cancelled' THEN
        RAISE_APPLICATION_ERROR(
            -20020,
            'Booking is already cancelled'
        );
    END IF;

    IF v_status NOT IN ('Pending', 'Confirmed') THEN
        RAISE_APPLICATION_ERROR(
            -20021,
            'Booking cannot be cancelled in its current status'
        );
    END IF;

    -- Check trip departure time
    IF v_departure_time <= SYSDATE THEN
        RAISE_APPLICATION_ERROR(
            -20022,
            'Cannot cancel a trip that has already started'
        );
    END IF;

    -- Check existing payments
    SELECT COUNT(*)
    INTO v_payment_count
    FROM PAYMENT
    WHERE BOOKING_ID = in_booking_id;

    IF v_payment_count > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20023,
            'Booking has a payment record and cannot be cancelled'
        );
    END IF;

    -- Cancel booking
    UPDATE BOOKING
    SET STATUS = 'Cancelled'
    WHERE BOOKING_ID = in_booking_id
      AND PASSENGER_ID = in_passenger_id;

    DBMS_OUTPUT.PUT_LINE(
        'Booking cancelled successfully.'
    );

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20024,
            'Booking not found for this passenger'
        );

    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(
            'Error: ' || SQLERRM
        );
        RAISE;
END Cancel_Passenger_Ticket;
