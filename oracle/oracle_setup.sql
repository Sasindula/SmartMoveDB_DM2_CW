CREATE OR REPLACE FUNCTION Get_Free_Seat_Count (
    in_trip_id IN NUMBER
)
RETURN NUMBER
IS
    v_capacity NUMBER;
    v_booked_seats NUMBER;
BEGIN
    -- Get vehicle capacity for the trip
    SELECT v.CAPACITY
    INTO v_capacity
    FROM TRIP t
    JOIN VEHICLE v
        ON t.VEHICLE_ID = v.VEHICLE_ID
    WHERE t.TRIP_ID = in_trip_id;

    -- Count occupied seats
    SELECT COUNT(*)
    INTO v_booked_seats
    FROM BOOKING
    WHERE TRIP_ID = in_trip_id
      AND STATUS IN (
          'Pending',
          'Confirmed',
          'Completed'
      );

    -- Return available seat count
    RETURN GREATEST(
        v_capacity - v_booked_seats,
        0
    );

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20030,
            'Trip does not exist'
        );

    WHEN OTHERS THEN
        RAISE;
END Get_Free_Seat_Count;
