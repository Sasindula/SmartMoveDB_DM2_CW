CREATE OR REPLACE PROCEDURE Fetch_Route_Usage_Stats
AS
    CURSOR c_route_summary IS
        SELECT
            r.ROUTE_ID,
            r.SOURCE,
            r.DESTINATION,
            COUNT(b.BOOKING_ID) AS TOTAL_BOOKINGS,
            COUNT(
                CASE
                    WHEN b.STATUS IN (
                        'Confirmed',
                        'Pending',
                        'Completed'
                    )
                    THEN 1
                END
            ) AS ACTIVE_BOOKINGS
        FROM ROUTE r
        LEFT JOIN TRIP t
            ON r.ROUTE_ID = t.ROUTE_ID
        LEFT JOIN BOOKING b
            ON t.TRIP_ID = b.TRIP_ID
        GROUP BY
            r.ROUTE_ID,
            r.SOURCE,
            r.DESTINATION
        ORDER BY TOTAL_BOOKINGS DESC;

BEGIN
    DBMS_OUTPUT.PUT_LINE(
        '===== MOST FREQUENTLY USED ROUTES ====='
    );

    FOR rec IN c_route_summary LOOP
        DBMS_OUTPUT.PUT_LINE(
            'Route #' || rec.ROUTE_ID ||
            ' | ' || rec.SOURCE ||
            ' -> ' || rec.DESTINATION ||
            ' | Total Bookings: ' || rec.TOTAL_BOOKINGS ||
            ' | Active Bookings: ' || rec.ACTIVE_BOOKINGS
        );
    END LOOP;

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(
            'Error: ' || SQLERRM
        );
        RAISE;
END Fetch_Route_Usage_Stats;
