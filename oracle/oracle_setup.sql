CREATE OR REPLACE PROCEDURE Show_Vehicles_In_Service
AS
    v_found BOOLEAN := FALSE;

    CURSOR c_maintenance IS
        SELECT
            v.VEHICLE_ID,
            v.PLATE_NUMBER,
            v.VEHICLE_TYPE,
            v.STATUS,
            m.MAINTENANCE_ID,
            m.MAINTENANCE_DATE,
            m.DESCRIPTION,
            m.COST
        FROM VEHICLE v
        LEFT JOIN MAINTENANCE m
            ON v.VEHICLE_ID = m.VEHICLE_ID
