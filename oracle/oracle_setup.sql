CREATE OR REPLACE FUNCTION Calc_Vehicle_Maint_Cost (
    in_vehicle_id IN NUMBER
)
RETURN NUMBER
IS
    v_exists NUMBER;
    v_total_cost NUMBER(12,2);
BEGIN
    -- Check whether the vehicle exists
    SELECT COUNT(*)
    INTO v_exists
    FROM VEHICLE
    WHERE VEHICLE_ID = in_vehicle_id;

    IF v_exists = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            'Vehicle does not exist'
        );
    END IF;

    -- Calculate total maintenance cost
    SELECT NVL(SUM(COST), 0)
    INTO v_total_cost
    FROM MAINTENANCE
    WHERE VEHICLE_ID = in_vehicle_id;

    RETURN v_total_cost;

EXCEPTION
    WHEN OTHERS THEN
        RAISE;
END Calc_Vehicle_Maint_Cost;
