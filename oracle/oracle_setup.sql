CREATE OR REPLACE PROCEDURE Show_Passenger_Logs (
    in_passenger_id IN NUMBER
)
AS
    v_exists NUMBER;

    CURSOR c_history IS
        SELECT
            b.BOOKING_ID,
            b.STATUS,
            r.SOURCE,
            r.DESTINATION,
            t.DEPARTURE_TIME,
            p.PAYMENT_ID,
            NVL(p.AMOUNT, 0) AS AMOUNT,
            NVL(p.PAYMENT_STATUS, 'Not Paid') AS PAYMENT_STATUS
        FROM BOOKING b
        JOIN TRIP t
            ON b.TRIP_ID = t.TRIP_ID
        JOIN ROUTE r
            ON t.ROUTE_ID = r.ROUTE_ID
        LEFT JOIN PAYMENT p
            ON b.BOOKING_ID = p.BOOKING_ID
        WHERE b.PASSENGER_ID = in_passenger_id
        ORDER BY t.DEPARTURE_TIME DESC;

BEGIN
    SELECT COUNT(*)
    INTO v_exists
    FROM PASSENGER
    WHERE PASSENGER_ID = in_passenger_id;

    IF v_exists = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20005,
            'Passenger does not exist'
        );
    END IF;

    FOR rec IN c_history LOOP
        DBMS_OUTPUT.PUT_LINE(
            'Booking #' || rec.BOOKING_ID ||
            ' | Route: ' || rec.SOURCE ||
            ' -> ' || rec.DESTINATION ||
            ' | Date: ' ||
            TO_CHAR(rec.DEPARTURE_TIME, 'YYYY-MM-DD HH24:MI') ||
            ' | Booking Status: ' || rec.STATUS ||
            ' | Amount: LKR ' || rec.AMOUNT ||
            ' | Payment: ' || rec.PAYMENT_STATUS
        );
    END LOOP;

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(
            'Error: ' || SQLERRM
        );
        RAISE;
END Show_Passenger_Logs;
