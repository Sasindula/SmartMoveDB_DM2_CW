-- 1. TABLE DEFINITIONS (dependency order; each table appears once)
CREATE TABLE Passenger (
    Passenger_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    First_Name VARCHAR2(50) NOT NULL,
    Last_Name VARCHAR2(50) NOT NULL,
    Email VARCHAR2(100) UNIQUE NOT NULL,
    Phone VARCHAR2(15) NOT NULL,
    Registration_Date DATE DEFAULT SYSDATE
);

CREATE TABLE Vehicle (
    Vehicle_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Plate_Number VARCHAR2(20) UNIQUE NOT NULL,
    Vehicle_Type VARCHAR2(20) CHECK (Vehicle_Type IN ('Bus', 'Van', 'Other')),
    Capacity NUMBER NOT NULL,
    Status VARCHAR2(20) DEFAULT 'Active' CHECK (Status IN ('Active', 'Maintenance', 'Inactive'))
);

CREATE TABLE Driver (
    Driver_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Driver_Name VARCHAR2(100) NOT NULL,
    License_Number VARCHAR2(50) UNIQUE NOT NULL,
    Phone VARCHAR2(15) NOT NULL,
    Status VARCHAR2(20) DEFAULT 'Active' CHECK (Status IN ('Active', 'On Trip', 'On Leave', 'Inactive'))
);

CREATE TABLE Route (
    Route_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Source VARCHAR2(100) NOT NULL,
    Destination VARCHAR2(100) NOT NULL,
    Distance_KM NUMBER(6,2) NOT NULL
);

CREATE TABLE Trip (
    Trip_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Route_ID NUMBER NOT NULL,
    Vehicle_ID NUMBER NOT NULL,
    Driver_ID NUMBER NOT NULL,
    Departure_Time TIMESTAMP NOT NULL,
    Arrival_Time TIMESTAMP NOT NULL,
    Fare_Amount NUMBER(8,2) NOT NULL,
    CONSTRAINT fk_trip_route FOREIGN KEY (Route_ID) REFERENCES Route(Route_ID),
    CONSTRAINT fk_trip_vehicle FOREIGN KEY (Vehicle_ID) REFERENCES Vehicle(Vehicle_ID),
    CONSTRAINT fk_trip_driver FOREIGN KEY (Driver_ID) REFERENCES Driver(Driver_ID)
);

CREATE TABLE Booking (
    Booking_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Trip_ID NUMBER NOT NULL,
    Passenger_ID NUMBER NOT NULL,
    Seat_Number VARCHAR2(10) NOT NULL,
    Booking_Date DATE DEFAULT SYSDATE,
    Status VARCHAR2(20) DEFAULT 'Confirmed' CHECK (Status IN ('Confirmed', 'Cancelled', 'Pending', 'Completed')),
    CONSTRAINT fk_booking_trip FOREIGN KEY (Trip_ID) REFERENCES Trip(Trip_ID),
    CONSTRAINT fk_booking_passenger FOREIGN KEY (Passenger_ID) REFERENCES Passenger(Passenger_ID)
);

CREATE TABLE Payment (
    Payment_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Booking_ID NUMBER UNIQUE NOT NULL,
    Amount NUMBER(8,2) NOT NULL,
    Payment_Method VARCHAR2(30) CHECK (Payment_Method IN ('Card', 'Cash', 'Online Transfer')),
    Payment_Date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Payment_Status VARCHAR2(20) DEFAULT 'Paid' NOT NULL,
    CONSTRAINT fk_payment_booking FOREIGN KEY (Booking_ID) REFERENCES Booking(Booking_ID)
);

CREATE TABLE Maintenance (
    Maintenance_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Vehicle_ID NUMBER NOT NULL,
    Maintenance_Date DATE NOT NULL,
    Description VARCHAR2(255),
    Cost NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_maint_vehicle FOREIGN KEY (Vehicle_ID) REFERENCES Vehicle(Vehicle_ID)
);

CREATE TABLE System_Users (
    User_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Username VARCHAR2(50) UNIQUE NOT NULL,
    Password_Hash VARCHAR2(255) NOT NULL,
    Role VARCHAR2(20) CHECK (Role IN ('ADMIN', 'DRIVER', 'PASSENGER')),
    Reference_ID NUMBER NULL, -- Refers to Passenger_ID or Driver_ID based on Role
    Created_At TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

