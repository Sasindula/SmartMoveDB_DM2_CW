CREATE OR REPLACE PROCEDURE Analyze_Payment_Channels
AS
    v_count NUMBER := 0;

    CURSOR c_payments IS
        SELECT
            PAYMENT_METHOD,
            COUNT(*) AS TOTAL_TRANSACTIONS,
            SUM(
                CASE
                    WHEN UPPER(PAYMENT_STATUS)
                         IN ('PAID', 'DEMO PAID')
                    THEN 1 ELSE 0
                END
            ) AS SUCCESSFUL_PAYMENTS,
            NVL(SUM(
                CASE
                    WHEN UPPER(PAYMENT_STATUS)
                         IN ('PAID', 'DEMO PAID')
                    THEN AMOUNT ELSE 0
                END
            ), 0) AS TOTAL_REVENUE
        FROM PAYMENT
        GROUP BY PAYMENT_METHOD
        ORDER BY TOTAL_REVENUE DESC;

BEGIN
    DBMS_OUTPUT.PUT_LINE(
        '===== PAYMENT CHANNEL ANALYSIS ====='
    );

    FOR rec IN c_payments LOOP
        v_count := v_count + 1;

        DBMS_OUTPUT.PUT_LINE(
            'Payment Method: ' || rec.PAYMENT_METHOD ||
            ' | Transactions: ' || rec.TOTAL_TRANSACTIONS ||
            ' | Successful: ' || rec.SUCCESSFUL_PAYMENTS ||
            ' | Revenue: LKR ' || rec.TOTAL_REVENUE
        );
    END LOOP;

    IF v_count = 0 THEN
        DBMS_OUTPUT.PUT_LINE(
            'No payment records found.'
        );
    END IF;

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(
            'Error: ' || SQLERRM
        );
        RAISE;
END Analyze_Payment_Channels;
